def send_message(
    db: Session,
    vendor_id: int,
    message: str,
    channel: str = "in_app",
) -> dict:
    """
    Send a message to a vendor and generate their reply.

    The outgoing message is stored first so it is not lost if reply
    generation fails.
    """

    vendor = db.query(VendorDB).filter(VendorDB.id == vendor_id).first()
    if vendor is None:
        raise HTTPException(status_code=404, detail="Vendor not found")

    now = datetime.utcnow()

    user_msg = ChatMessageDB(
        vendor_id=vendor_id,
        sender="user",
        message=message,
        status="sent",
        channel=channel,
        timestamp=now,
    )
    db.add(user_msg)
    db.commit()
    db.refresh(user_msg)

    # Generated after the commit above so history includes this message.
    reply_text, source = _generate_vendor_reply(db, vendor, message)

    vendor_msg = ChatMessageDB(
        vendor_id=vendor_id,
        sender="vendor",
        message=reply_text,
        status="delivered",
        channel=channel,
        timestamp=datetime.utcnow(),
    )
    db.add(vendor_msg)
    db.commit()
    db.refresh(vendor_msg)

    return {
        "user_message": {
            "id": user_msg.id,
            "sender": "user",
            "message": user_msg.message,
            "channel": user_msg.channel,
            "status": user_msg.status,
            "timestamp": user_msg.timestamp.isoformat(),
        },
        "vendor_reply": {
            "id": vendor_msg.id,
            "sender": "vendor",
            "message": vendor_msg.message,
            "channel": vendor_msg.channel,
            "status": vendor_msg.status,
            "timestamp": vendor_msg.timestamp.isoformat(),
        },
        "generated_by": source,
    }


def stream_message(
    db: Session,
    vendor_id: int,
    message: str,
    channel: str = "in_app",
) -> Generator[dict, None, None]:
    """
    Same contract as `send_message`, but yields incremental events so the
    caller (an SSE endpoint) can render the vendor's reply as it is typed
    instead of waiting for the full generation.

    Yields dicts of the form:
        {"type": "user_message", "message": {...}}
        {"type": "token", "content": "..."}          (repeated)
        {"type": "done", "vendor_reply": {...}, "generated_by": "llm"|"fallback"}

    The user's message is persisted before any tokens are yielded, matching
    `send_message`'s guarantee that an outgoing message is never lost even
    if generation fails partway through.

    Note: unlike `send_message`, streamed text is not retroactively
    quote-stripped, since tokens are already on the wire by the time the
    full text is known. In practice the model rarely wraps replies in
    quotes when instructed not to, so this is a cosmetic edge case.
    """

    vendor = db.query(VendorDB).filter(VendorDB.id == vendor_id).first()
    if vendor is None:
        raise HTTPException(status_code=404, detail="Vendor not found")

    now = datetime.utcnow()

    user_msg = ChatMessageDB(
        vendor_id=vendor_id,
        sender="user",
        message=message,
        status="sent",
        channel=channel,
        timestamp=now,
    )
    db.add(user_msg)
    db.commit()
    db.refresh(user_msg)

    yield {
        "type": "user_message",
        "message": {
            "id": user_msg.id,
            "sender": "user",
            "message": user_msg.message,
            "channel": user_msg.channel,
            "status": user_msg.status,
            "timestamp": user_msg.timestamp.isoformat(),
        },
    }

    fleet_context = _build_vendor_context(db, vendor)
    history = _conversation_history(db, vendor.id)
    history.append({"role": "user", "content": message})

    accumulated = ""

    for piece in llm.chat_stream(
        system_prompt=_vendor_system_prompt(vendor, fleet_context),
        messages=history,
        temperature=0.8,
        max_tokens=256,
    ):
        accumulated += piece
        yield {"type": "token", "content": piece}

    if accumulated.strip():
        reply_text = accumulated.strip()
        source = "llm"
    else:
        # Stream produced nothing (model down or errored) — fall back and
        # emit the whole fallback reply as a single token so the UI still
        # renders it through the same code path.
        logger.info("LLM stream unavailable, using keyword fallback for vendor %s", vendor.id)
        reply_text = _keyword_reply(message)
        source = "fallback"
        yield {"type": "token", "content": reply_text}

    vendor_msg = ChatMessageDB(
        vendor_id=vendor_id,
        sender="vendor",
        message=reply_text,
        status="delivered",
        channel=channel,
        timestamp=datetime.utcnow(),
    )
    db.add(vendor_msg)
    db.commit()
    db.refresh(vendor_msg)

    yield {
        "type": "done",
        "vendor_reply": {
            "id": vendor_msg.id,
            "sender": "vendor",
            "message": vendor_msg.message,
            "channel": vendor_msg.channel,
            "status": vendor_msg.status,
            "timestamp": vendor_msg.timestamp.isoformat(),
        },
        "generated_by": source,
    }


def get_chat_history(
    db: Session,
    vendor_id: int,
    limit: int = 50,
) -> list[dict]:
    """Return conversation thread with a vendor."""

    messages = (
        db.query(ChatMessageDB)
        .filter(ChatMessageDB.vendor_id == vendor_id)
        .order_by(ChatMessageDB.timestamp.asc())
        .limit(limit)
        .all()
    )

    return [
        {
            "id": m.id,
            "sender": m.sender,
            "message": m.message,
            "channel": m.channel,
            "status": m.status,
            "timestamp": m.timestamp.isoformat(),
        }
        for m in messages
    ]


