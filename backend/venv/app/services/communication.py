def _generate_call_transcript(
    db: Session,
    vendor: VendorDB,
) -> tuple[str, str, int, str]:
    """
    Generate an AI voice call transcript and summary.

    Returns:
        (transcript, summary, duration_seconds, source)
    """

    fleet_context = _build_vendor_context(db, vendor)

    transcript_prompt = f"""You are writing a realistic transcript of a short phone call between an AI assistant and a crane rental vendor in Pune, India.

The AI assistant works for FleetTrack, a fleet management system. It is calling {vendor.name} of {vendor.company} for a routine status update on their crane.

{fleet_context}

Write the transcript with these rules:
- Alternate lines prefixed exactly "AI:" and "Vendor:".
- 6 to 8 lines total.
- The AI opens by identifying itself and naming a specific crane from the list above.
- The vendor gives a concrete operational update: what the crane is doing, where, and any issue.
- Include one realistic detail such as a maintenance need, a delay, or a schedule change.
- The AI closes politely.
- Plain text only. No markdown, no stage directions, no commentary.

Output only the transcript lines."""

    transcript = llm.chat(
        system_prompt="You write concise, realistic phone call transcripts.",
        messages=[{"role": "user", "content": transcript_prompt}],
        temperature=0.8,
        max_tokens=400,
        timeout=llm.TRANSCRIPT_TIMEOUT,
    )

    if not transcript:
        logger.info("LLM unavailable, using fallback transcript for vendor %s", vendor.id)
        mock = random.choice(_FALLBACK_CALLS)
        return mock["transcript"], mock["summary"], mock["duration"], "fallback"

    transcript = transcript.strip()

    summary = llm.chat(
        system_prompt="You summarise phone calls for a fleet operations log.",
        messages=[
            {
                "role": "user",
                "content": (
                    "Summarise this call in 1 to 2 sentences. State the crane's current "
                    "status and any action item. Plain text only, no preamble.\n\n"
                    f"{transcript}"
                ),
            }
        ],
        temperature=0.3,
        max_tokens=120,
    )

    if not summary:
        # Transcript succeeded but summary did not — derive a minimal one
        # rather than discarding a good transcript.
        summary = "Call completed. See transcript for details."
    else:
        summary = summary.strip().strip('"').strip()

    # Estimate duration from transcript length at a natural speaking pace.
    word_count = len(transcript.split())
    duration = max(20, min(120, int(word_count / 2.5)))

    return transcript, summary, duration, "llm"


def initiate_voice_call(
    db: Session,
    vendor_id: int,
) -> dict:
    """
    Run an AI voice call to a vendor.

    The conversation is generated by the local LLM; the telephony leg is
    mocked. To go live: replace `_generate_call_transcript` with a Twilio or
    Bland.ai outbound call, persist the provider call SID in
    `external_call_id`, and update the record from the provider's completion
    webhook.
    """

    vendor = db.query(VendorDB).filter(VendorDB.id == vendor_id).first()
    if vendor is None:
        raise HTTPException(status_code=404, detail="Vendor not found")

    transcript, summary, duration, source = _generate_call_transcript(db, vendor)

    now = datetime.utcnow()

    call = VoiceCallDB(
        vendor_id=vendor_id,
        direction="outbound",
        call_status="completed",
        duration_seconds=duration,
        transcript=transcript,
        summary=summary,
        external_call_id=f"CALL-{uuid.uuid4().hex[:10].upper()}",
        initiated_at=now,
        completed_at=now,
    )

    db.add(call)
    db.commit()
    db.refresh(call)

    return {
        "id": call.id,
        "vendor_id": call.vendor_id,
        "vendor_name": vendor.name,
        "vendor_phone": vendor.phone,
        "direction": call.direction,
        "call_status": call.call_status,
        "duration_seconds": call.duration_seconds,
        "transcript": call.transcript,
        "summary": call.summary,
        "external_call_id": call.external_call_id,
        "initiated_at": call.initiated_at.isoformat(),
        "completed_at": call.completed_at.isoformat() if call.completed_at else None,
        "generated_by": source,
    }


def get_call_history(
    db: Session,
    vendor_id: int | None = None,
    limit: int = 20,
) -> list[dict]:
    """Return voice call logs, optionally filtered by vendor."""

    query = db.query(VoiceCallDB)

    if vendor_id is not None:
        query = query.filter(VoiceCallDB.vendor_id == vendor_id)

    calls = (
        query.order_by(VoiceCallDB.initiated_at.desc())
        .limit(limit)
        .all()
    )

    results = []

    for c in calls:
        vendor = db.query(VendorDB).filter(VendorDB.id == c.vendor_id).first()

        results.append({
            "id": c.id,
            "vendor_id": c.vendor_id,
            "vendor_name": vendor.name if vendor else "Unknown",
            "vendor_phone": vendor.phone if vendor else "",
            "direction": c.direction,
            "call_status": c.call_status,
            "duration_seconds": c.duration_seconds,
            "transcript": c.transcript,
            "summary": c.summary,
            "external_call_id": c.external_call_id,
            "initiated_at": c.initiated_at.isoformat(),
            "completed_at": c.completed_at.isoformat() if c.completed_at else None,
        })

    return results
