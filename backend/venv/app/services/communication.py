def _generate_call_transcript(
    db: Session,
    vendor: VendorDB,
) -> tuple[str, str, int, str]:
    """
    Generate an AI voice call transcript and summary.

    Returns:
        (transcript, summary, duration_seconds, source)
    """

    fleet_context = _build_vendor_context(db, vendor)

    transcript_prompt = f"""You are writing a realistic transcript of a phone call between an AI voice agent and a crane rental vendor in Pune, India.

The AI voice agent works for FleetTrack, a fleet management system. It is calling {vendor.name} of {vendor.company} ({vendor.phone}) for a routine status update.

{fleet_context}

CALL SCRIPT — the AI agent follows this structure:

1. OPENING: The AI identifies itself as FleetTrack, confirms it is speaking with {vendor.name}, and states which crane it is calling about (pick one from the list above that has an active booking or is in an interesting state like repair).

2. OPERATIONAL STATUS: The AI asks if the crane is operational and working as expected.

3. WORK PROGRESS: The AI asks what work is currently being done and if there is a progress update.

4. ISSUES / MAINTENANCE: The AI asks about any mechanical issues, maintenance needs, or concerns.

5. TIMELINE: If the crane has an active booking, the AI asks if work is on track to complete by the end date.

6. CLOSING: The AI thanks the vendor and says it will log the update in the system.

VENDOR RESPONSES should be:
- Professional but natural — a busy site owner giving brief, honest answers
- Include one concrete detail: a specific task being done, a part that needs attention, or a schedule note
- Occasionally mention a minor issue or upcoming need (hydraulic check, cable inspection, operator shift change)

FORMAT RULES:
- Alternate lines prefixed exactly "AI:" and "Vendor:" — no other prefixes or labels
- 8 to 12 lines total (4 to 6 exchanges)
- Plain text only. No markdown, no stage directions, no asterisks, no commentary
- The AI is polite and professional, addresses vendor as "sir" or by name
- Keep total call feel around 60-90 seconds of real speech

Output only the transcript lines, nothing else."""

    transcript = llm.chat(
        system_prompt="You write concise, realistic phone call transcripts.",
        messages=[{"role": "user", "content": transcript_prompt}],
        temperature=0.8,
        max_tokens=400,
        timeout=llm.TRANSCRIPT_TIMEOUT,
    )

    if not transcript:
        logger.info("LLM unavailable, using fallback transcript for vendor %s", vendor.id)
        mock = random.choice(_FALLBACK_CALLS)
        return mock["transcript"], mock["summary"], mock["duration"], "fallback"

    transcript = transcript.strip()

    summary = llm.chat(
        system_prompt="You summarise phone calls for a fleet operations log. Be structured and concise.",
        messages=[
            {
                "role": "user",
                "content": (
                    "Summarise this call in a structured format:\n"
                    "- Crane: [name and ID]\n"
                    "- Status: [Operational / Under Repair / Idle]\n"
                    "- Update: [1-2 sentence summary of what was discussed]\n"
                    "- Issues: [None / brief description]\n"
                    "- Action Items: [any follow-ups needed, or None]\n\n"
                    "Plain text only, no markdown, no preamble. Just the summary lines.\n\n"
                    f"{transcript}"
                ),
            }
        ],
        temperature=0.3,
        max_tokens=200,
    )

    if not summary:
        # Transcript succeeded but summary did not — derive a minimal one
        # rather than discarding a good transcript.
        summary = "Call completed. See transcript for details."
    else:
        summary = summary.strip().strip('"').strip()

    # Estimate duration from transcript length at a natural speaking pace.
    word_count = len(transcript.split())
    duration = max(20, min(120, int(word_count / 2.5)))

    return transcript, summary, duration, "llm"


def _pick_call_context(db: Session, vendor: VendorDB) -> dict:
    """
    Choose the most relevant crane + booking to talk about on a call.

    Preference order:
      1. A crane with an active/confirmed booking (most to discuss)
      2. Any crane the vendor owns
      3. Nothing (generic fallback fields)

    Returns the fields the external voice service expects.
    """

    cranes = (
        db.query(EquipmentDB)
        .filter(EquipmentDB.vendor_id == vendor.id)
        .all()
    )

    chosen_crane = None
    chosen_booking = None

    for crane in cranes:
        booking = (
            db.query(BookingDB)
            .filter(
                BookingDB.crane_id == crane.id,
                BookingDB.booking_status.in_(["confirmed", "active"]),
            )
            .first()
        )
        if booking is not None:
            chosen_crane = crane
            chosen_booking = booking
            break

    if chosen_crane is None and cranes:
        chosen_crane = cranes[0]

    if chosen_crane is None:
        # Vendor owns no cranes — still give the service usable defaults.
        return {
            "crane_name": "your crane",
            "crane_id": "",
            "booking_status": "a routine status check",
            "client_site": vendor.company,
            "end_date": "the scheduled date",
        }

    if chosen_booking is not None:
        booking_status = "an active booking to lift heavy equipment at your site"
        client_site = chosen_booking.site_address or vendor.company
        end_date = chosen_booking.end_date.strftime("%d %b %Y")
    else:
        booking_status = f"currently {chosen_crane.lifecycle_status}"
        client_site = vendor.company
        end_date = "not scheduled"

    return {
        "crane_name": chosen_crane.name,
        "crane_id": chosen_crane.id,
        "booking_status": booking_status,
        "client_site": client_site,
        "end_date": end_date,
    }


def _place_real_call(vendor: VendorDB, context: dict) -> dict:
    """
    Place a real outbound AI call via the external voice service.

    Returns the service's JSON response. Raises HTTPException(503) on any
    failure — there is no local fallback, so a failure here means the call
    genuinely could not be placed and the caller/UI should report the voice
    channel as unavailable.
    """

    if not VOICE_CALL_SERVICE_URL:
        raise HTTPException(
            status_code=503,
            detail="Voice calling is not configured (VOICE_CALL_SERVICE_URL unset).",
        )

    payload = {
        "phone_number": vendor.phone,
        "vendor_name": vendor.name,
        "crane_name": context["crane_name"],
        "crane_id": context["crane_id"],
        "booking_status": context["booking_status"],
        "client_site": context["client_site"],
        "end_date": context["end_date"],
    }

    try:
        response = requests.post(
            VOICE_CALL_SERVICE_URL,
            json=payload,
            timeout=VOICE_CALL_TIMEOUT,
        )
        response.raise_for_status()
        return response.json()

    except requests.RequestException as exc:
        logger.warning("Voice call service request failed: %s", exc)
        raise HTTPException(
            status_code=503,
            detail="The voice channel is busy right now. Please try again in a moment.",
        )
    except ValueError as exc:
        logger.warning("Voice call service returned non-JSON: %s", exc)
        raise HTTPException(
            status_code=502,
            detail="The voice service returned an unexpected response.",
        )


def initiate_voice_call(
    db: Session,
    vendor_id: int,
) -> dict:
    """
    Place a real outbound AI voice call to a vendor via the external voice
    service.

    No local fallback: if the service is not configured or the call cannot be
    placed, this raises an HTTPException so the UI reports the voice channel
    as unavailable. The generated-transcript path has been removed.

    The transcript is not available synchronously — it is filled in later when
    the voice service reports call completion (via the /voice/calls/{id}
    webhook). The record is created in an in_progress state.
    """

    vendor = db.query(VendorDB).filter(VendorDB.id == vendor_id).first()
    if vendor is None:
        raise HTTPException(status_code=404, detail="Vendor not found")

    context = _pick_call_context(db, vendor)

    # Raises HTTPException(503/502) on any failure — no fallback.
    service_result = _place_real_call(vendor, context)

    now = datetime.utcnow()

    # The service returns identifiers under various keys depending on provider.
    external_id = (
        service_result.get("call_sid")
        or service_result.get("call_id")
        or service_result.get("id")
        or f"CALL-{uuid.uuid4().hex[:10].upper()}"
    )
    service_status = str(service_result.get("status", "initiated"))
    failed = service_status.lower() in ("failed", "error")

    call = VoiceCallDB(
        vendor_id=vendor_id,
        direction="outbound",
        call_status="failed" if failed else "in_progress",
        duration_seconds=0,
        transcript=(
            f"Live AI call placed to {vendor.phone} regarding "
            f"{context['crane_name']} ({context['crane_id']}). "
            f"Provider status: {service_status}. "
            "Transcript will be available once the call completes."
        ),
        summary=(
            f"Outbound AI call to {vendor.name} about "
            f"{context['crane_name']} — awaiting completion."
        ),
        external_call_id=str(external_id),
        initiated_at=now,
        completed_at=None,
    )

    db.add(call)
    db.commit()
    db.refresh(call)

    return {
        "id": call.id,
        "vendor_id": call.vendor_id,
        "vendor_name": vendor.name,
        "vendor_phone": vendor.phone,
        "direction": call.direction,
        "call_status": call.call_status,
        "duration_seconds": call.duration_seconds,
        "transcript": call.transcript,
        "summary": call.summary,
        "external_call_id": call.external_call_id,
        "initiated_at": call.initiated_at.isoformat(),
        "completed_at": None,
        "generated_by": "live_call",
    }


def get_call_history(
    db: Session,
    vendor_id: int | None = None,
    limit: int = 20,
) -> list[dict]:
    """Return voice call logs, optionally filtered by vendor."""

    query = db.query(VoiceCallDB)

    if vendor_id is not None:
        query = query.filter(VoiceCallDB.vendor_id == vendor_id)

    calls = (
        query.order_by(VoiceCallDB.initiated_at.desc())
        .limit(limit)
        .all()
    )

    results = []

    for c in calls:
        vendor = db.query(VendorDB).filter(VendorDB.id == c.vendor_id).first()

        results.append({
            "id": c.id,
            "vendor_id": c.vendor_id,
            "vendor_name": vendor.name if vendor else "Unknown",
            "vendor_phone": vendor.phone if vendor else "",
            "direction": c.direction,
            "call_status": c.call_status,
            "duration_seconds": c.duration_seconds,
            "transcript": c.transcript,
            "summary": c.summary,
            "external_call_id": c.external_call_id,
            "initiated_at": c.initiated_at.isoformat(),
            "completed_at": c.completed_at.isoformat() if c.completed_at else None,
        })

    return results
