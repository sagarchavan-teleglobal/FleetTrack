import os
import random
import uuid
from datetime import datetime
from typing import Generator

import requests
from fastapi import HTTPException
from sqlalchemy.orm import Session

from app.db_models import BookingDB, ChatMessageDB, EquipmentDB, VendorDB, VoiceCallDB
from app.services import llm

logger = logging.getLogger(__name__)


# --------------------------------------------------
# External voice-call service (real AI outbound calls)
# --------------------------------------------------
#
# When VOICE_CALL_SERVICE_URL is set, the "Call Vendor" action places a real
# outbound AI phone call through this service instead of generating a mock
# transcript locally. The service dials the vendor, runs the conversation,
# and (in a full integration) reports the transcript back via webhook.
#
# Set VOICE_CALL_SERVICE_URL to the /call/initiate endpoint, e.g.
#   http://3.92.238.46:8002/call/initiate

VOICE_CALL_SERVICE_URL = os.getenv("VOICE_CALL_SERVICE_URL", "")
VOICE_CALL_TIMEOUT = 30


# --------------------------------------------------
# Static fallback replies (used when the LLM is down)
# --------------------------------------------------

_STATUS_REPLIES = [
    "Crane is on-site at Hinjewadi Phase 3. Operator reports normal operations.",
    "Currently in transit to the site. ETA 45 minutes.",
    "Maintenance complete. Crane will be back online by tomorrow morning.",
    "All good here. Working on the 4th floor lifting today.",
    "Minor hydraulic issue detected. Engineer dispatched, should be fixed in 2 hours.",
    "Crane is idle today — waiting for materials to arrive on site.",
]

_GENERAL_REPLIES = [
    "Got it, will update you shortly.",
    "Thanks for the message. I'll check with the operator.",
    "Noted. Will send photos of the site progress by EOD.",
    "Understood. I'll coordinate with the site supervisor.",
    "OK, I'll make sure the operator knows.",
]


def _keyword_reply(message: str) -> str:
    """Deterministic keyword-matched reply. Fallback when the LLM is down."""

    lower = message.lower()

    if any(word in lower for word in ["status", "update", "progress", "where"]):
        return random.choice(_STATUS_REPLIES)

    if any(word in lower for word in ["available", "free", "book"]):
        return "Let me check the schedule and get back to you within the hour."

    if any(word in lower for word in ["repair", "maintenance", "fix", "broken"]):
        return "I'll send our technician immediately. He should reach in about 30 minutes."

    if any(word in lower for word in ["payment", "invoice", "bill"]):
        return "Invoice has been sent to your registered email. Let me know if you need a revised one."

    return random.choice(_GENERAL_REPLIES)


# --------------------------------------------------
# Fleet context for the LLM
# --------------------------------------------------

def _build_vendor_context(db: Session, vendor: VendorDB) -> str:
    """
    Summarise the vendor's fleet and bookings as plain text for the prompt.

    Giving the model concrete equipment IDs, rates, and customer names keeps
    replies specific instead of generic.
    """

    cranes = (
        db.query(EquipmentDB)
        .filter(EquipmentDB.vendor_id == vendor.id)
        .all()
    )

    if not cranes:
        return "You currently have no cranes registered in the system."

    lines = ["Your cranes currently in the system:"]

    for crane in cranes:
        detail = (
            f"- {crane.name} ({crane.id}): "
            f"lifecycle status '{crane.lifecycle_status}', "
            f"live telemetry '{crane.status}', "
            f"rate Rs.{crane.hourly_rate:.0f}/hr"
        )

        booking = (
            db.query(BookingDB)
            .filter(
                BookingDB.crane_id == crane.id,
                BookingDB.booking_status.in_(["confirmed", "active"]),
            )
            .first()
        )

        if booking is not None:
            detail += (
                f", booked by {booking.customer_name}"
                f" at {booking.site_address or 'site not specified'}"
                f" until {booking.end_date.strftime('%d %b %Y')}"
            )

        lines.append(detail)

    return "\n".join(lines)


def _vendor_system_prompt(vendor: VendorDB, fleet_context: str) -> str:
    """Persona instructions for vendor chat replies."""

    return f"""You are {vendor.name}, owner of {vendor.company}, a crane and heavy equipment rental business in Pune, India. Your contact number is {vendor.phone}.

You are chatting on WhatsApp with a fleet manager who rents cranes from you.

{fleet_context}

Your personality and tone:
- You are a busy, experienced construction equipment owner. You've been in this business 15+ years.
- You communicate professionally but warmly — like a trusted business partner, not a customer service bot.
- Keep replies brief and clear: 1-3 sentences. This is WhatsApp, not email.
- Use natural Indian business English. Occasional Hindi words are fine when they feel natural (like "ji", "theek hai", "sure sir") but do not overdo it. Most replies should be in proper English.
- Sound confident and knowledgeable about your equipment.
- Reference specific cranes by name when relevant.
- Use "Rs." for amounts.
- If you don't have the information, say you'll check and confirm — don't guess.
- Never use markdown, bullet points, numbered lists, or emoji.
- Never reveal you are an AI.

IMPORTANT: Only state facts that appear in the crane data above. Do not invent site names, times, dates, or issues that are not mentioned in the data. If asked about something not covered, defer politely.

Example exchanges (for tone reference only, not facts):
Fleet manager: "How's the crane at the site doing?"
You: "All good sir, crane is running smoothly. No issues reported so far."

Fleet manager: "Need a crane urgently, anything free?"
You: "Yes, Tower Crane Alpha is available at Rs.2500/hr. Let me know and I'll arrange dispatch."

Fleet manager: "The GPS is showing offline, what happened?"
You: "Let me check with the operator. Could be a signal issue in the area, I'll revert shortly."

Fleet manager: "Can you send the invoice?"
You: "Sure, will send it by tomorrow. Was caught up today."

Reply with only the message text, nothing else."""


def _conversation_history(
    db: Session,
    vendor_id: int,
    limit: int = 10,
) -> list[dict]:
    """
    Recent turns formatted for the LLM.

    The fleet manager is 'user'; the vendor (the persona the model plays) is
    'assistant'. Only the last `limit` messages are included to keep the
    prompt small and generation fast.
    """

    recent = (
        db.query(ChatMessageDB)
        .filter(ChatMessageDB.vendor_id == vendor_id)
        .order_by(ChatMessageDB.id.desc())
        .limit(limit)
        .all()
    )

    return [
        {
            "role": "user" if m.sender == "user" else "assistant",
            "content": m.message,
        }
        for m in reversed(recent)
    ]


def _generate_vendor_reply(
    db: Session,
    vendor: VendorDB,
    message: str,
) -> tuple[str, str]:
    """
    Generate the vendor's reply.

    Returns:
        (reply_text, source) where source is "llm" or "fallback".
    """

    fleet_context = _build_vendor_context(db, vendor)

    history = _conversation_history(db, vendor.id)
    history.append({"role": "user", "content": message})

    reply = llm.chat(
        system_prompt=_vendor_system_prompt(vendor, fleet_context),
        messages=history,
        temperature=0.8,
        max_tokens=256,
    )

    if reply:
        # Strip quotes the model sometimes wraps around the message.
        return reply.strip().strip('"').strip(), "llm"

    logger.info("LLM unavailable, using keyword fallback for vendor %s", vendor.id)
    return _keyword_reply(message), "fallback"


